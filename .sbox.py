def gmul(a,b):
    r=0
    for _ in range(8):
        if b&1: r^=a
        hi=a&0x80
        a=(a<<1)&0xff
        if hi: a^=0x1b
        b>>=1
    return r
def ginv(a):
    res=1; base=a; e=254
    while e:
        if e&1: res=gmul(res,base)
        base=gmul(base,base)
        e>>=1
    return res
def rotl8(x,n): return ((x<<n)|(x>>(8-n)))&0xff
